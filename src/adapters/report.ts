import { analyzeAutomationRisks } from "../core/analyzer.ts";
import type { AutomationManifest } from "../core/types.ts";

/**
 * Generates a comprehensive GitHub Flavored Markdown audit report for an automation manifest.
 */
export function generateMarkdownAuditReport(manifest: AutomationManifest): string {
  const audit = analyzeAutomationRisks(manifest);

  const lines: string[] = [
    `# Pre-Flight Safety Audit Report: ${manifest.name}`,
    ``,
    `| Attribute | Value |`,
    `|---|---|`,
    `| **Automation ID** | \`${manifest.id}\` |`,
    `| **Version** | \`v${manifest.version}\` |`,
    `| **Author** | ${manifest.author} |`,
    `| **Category** | \`${manifest.category}\` |`,
    `| **Safety Grade** | **${audit.safetyGrade}** (Risk Index: ${audit.riskIndex}/100) |`,
    `| **HA Minimum Core** | \`>= ${manifest.platform.minCoreVersion}\` |`,
    `| **Rollback Complete** | ${audit.rollbackComplete ? "✅ Yes" : "❌ Incomplete"} |`,
    ``,
    `## 📋 Pre-Flight Safety Checklist`,
    ``,
    ...audit.preFlightChecklist.map((item) => `- [ ] ${item}`),
    ``,
    `## ⚠️ Identified Hazards & Safety Mitigations`,
    ``,
    `| Category | Severity | Hazard Description | Enforced Mitigation |`,
    `|---|---|---|---|`,
    ...manifest.risks.map(
      (r) =>
        `| \`${r.category}\` | **${r.severity.toUpperCase()}** | ${r.description} | ${r.mitigation} |`
    ),
    ``,
    `## 🔄 Rollback & Emergency Restoration Procedure`,
    ``,
    `- **Emergency Quick Disable**: ${manifest.rollback.quickDisable}`,
    `- **Estimated Recovery Time**: ~${manifest.rollback.estimatedRecoverySeconds}s`,
    `- **Step-by-Step Restoration**:`,
    ...manifest.rollback.stateRestoration.map((s, idx) => `  ${idx + 1}. ${s}`),
    `- **Hardware Fallback**: ${manifest.rollback.fallbackProcedure}`,
    ``,
  ];

  if (audit.violations.length > 0) {
    lines.push(`## 🚨 Safety Rule Violations`);
    lines.push(``);
    for (const v of audit.violations) {
      lines.push(`### [${v.severity.toUpperCase()}] ${v.ruleId}`);
      lines.push(`- **Issue**: ${v.message}`);
      lines.push(`- **Remediation**: ${v.remediation}`);
      lines.push(``);
    }
  }

  lines.push(`---`);
  lines.push(`*Generated by [AutomationMarketplace](https://github.com/MRJonam91/AutomationMarketplace) — Deterministic Smart Home Safety Guard.*`);

  return lines.join("\n") + "\n";
}
